// Command plugin-registry generates static imports for ordinary Go plugin packages.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"io/fs"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

func main() {
	root := flag.String("root", ".", "module root")
	output := flag.String("output", "pluginregistry/generated.go", "output relative to module root")
	flag.Parse()
	if err := generate(*root, *output); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
func generate(root, output string) error {
	mod, err := os.ReadFile(filepath.Join(root, "go.mod"))
	if err != nil {
		return err
	}
	module := ""
	for line := range strings.SplitSeq(string(mod), "\n") {
		fields := strings.Fields(line)
		if len(fields) == 2 && fields[0] == "module" {
			module = fields[1]
			break
		}
	}
	if module == "" {
		return fmt.Errorf("module directive missing")
	}
	packages := map[string]bool{}
	err = filepath.WalkDir(filepath.Join(root, "plugins"), func(path string, d fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if d.IsDir() {
			if d.Name() == "testdata" || strings.HasPrefix(d.Name(), ".") {
				return filepath.SkipDir
			}
			return nil
		}
		if !strings.HasSuffix(path, ".go") || strings.HasSuffix(path, "_test.go") {
			return nil
		}
		file, err := parser.ParseFile(token.NewFileSet(), path, nil, 0)
		if err != nil {
			return err
		}
		for _, decl := range file.Decls {
			fn, ok := decl.(*ast.FuncDecl)
			if ok && fn.Recv == nil && fn.Name.Name == "Definition" {
				rel, err := filepath.Rel(root, filepath.Dir(path))
				if err != nil {
					return err
				}
				if rel == "plugins" {
					continue
				}
				packages[module+"/"+filepath.ToSlash(rel)] = true
			}
		}
		return nil
	})
	if err != nil {
		return err
	}
	paths := []string{}
	for path := range packages {
		paths = append(paths, path)
	}
	sort.Strings(paths)
	var out bytes.Buffer
	fmt.Fprint(&out, "// Code generated by go generate ./pluginregistry; DO NOT EDIT.\npackage pluginregistry\nimport (\nsdk "+strconv.Quote(module+"/plugins")+"\n")
	for i, path := range paths {
		fmt.Fprintf(&out, "p%d %q\n", i, path)
	}
	fmt.Fprint(&out, ")\n\n// New returns the compiled catalog, rejecting duplicate or invalid definitions.\nfunc New() (*sdk.Registry,error) {\nr := sdk.NewRegistry()\n")
	for i := range paths {
		fmt.Fprintf(&out, "if err:=r.Register(p%d.Definition());err!=nil{return nil,err}\n", i)
	}
	fmt.Fprint(&out, "return r,nil\n}\n")
	code, err := format.Source(out.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(root, output), code, 0644)
}
